#!/usr/bin/env python3
"""Generate the QBF formulation of Section 4.2 ("Formal verification by QBF") in QDIMACS format.

The formula states that an AND protocol with mixed encoding exists in the following
class.  The input sequence is (a, b, not b) with three working cards, or
(club, a, b, not b) with four working cards: Alice's input a is a single-card
commitment, and Bob's input b is a two-card commitment.  For l = 1, ..., k, the
protocol applies a rearrangement (perm, pi_l) followed by a shuffle (shuffle, Pi_l, F_l).
After the last shuffle, it turns the cards in a fixed set T with |T| <= n-1 and
outputs the card at a position R(T, v) outside T that depends on the symbols v of
the turned cards.

Formula (1) of the paper, with possibilistic security:
    exists P  forall a,b,O  exists X  forall a',b'  exists O',X':
        Protocol(P) & [Valid(O) -> (Trace(a,b,O,X) & Correct(a,b,X)
                                     & Valid(O') & Trace(a',b',O',X') & Same(X,X'))]
Formula (2), correctness only (option --no-security):
    exists P  forall a,b,O  exists X:
        Protocol(P) & [Valid(O) -> (Trace(a,b,O,X) & Correct(a,b,X))]

Variables, in the order of the quantifier prefix (code name: name in the paper):
    exists  s[l][i]: s_{l,pi},  m[l][i]: m_{l,pi},  c[l][S]: c_{l,Pi},
            u[T]: u_T,  r[T, v][p]: r_{T,v,i}                      (the protocol P)
    forall  a, b, and F[l]: the bits of O_l, which encode the l-th outcome in binary
    exists  x0[j]: x^(0)_j,  y[l][j]: y^(l)_j,  x[l][j]: x^(l)_j,  z   (the execution X)
            e[l][i], w[l], g: auxiliary variables of the CNF translation
    forall  a2, b2: a', b'
    exists  e2[l][i]: e'_{l,pi}, and the card variables of X'
Card values: 0 = club, 1 = heart.  Positions are 0-based in the code and 1-based in
the paper and in all printed output.  A permutation p (a tuple) moves the card at
position j to position p[j].

By Proposition 4.6 of the paper, formula (1) is true if and only if some protocol of
the class computes AND with possibilistic security.  So a false formula rules out
secure protocols of the class, for any probability distributions of the shuffles.
"""
import argparse
import itertools
import math

# Input sequences: (number of cards, source of each position).
# ('a', 0) holds a; ('b', 0) holds b; ('b', 1) holds not b; ('c', v) is a helping card of value v.
LAYOUTS = {
    3: (3, [('a', 0), ('b', 0), ('b', 1)]),              # (a, b, not b)
    4: (4, [('c', 0), ('a', 0), ('b', 0), ('b', 1)]),    # (club, a, b, not b), as in Mizuki (2016)
}

SHUFFLE_CLASSES = ('transposition', 'rbc', 'closed', 'rc', 'arbitrary')


def all_perms(n):
    return list(itertools.permutations(range(n)))


def compose(p, q):
    """(p o q)(j) = p(q(j))."""
    return tuple(p[q[j]] for j in range(len(q)))


def generated_group(gens, n):
    identity = tuple(range(n))
    group, todo = {identity}, [identity]
    while todo:
        g = todo.pop()
        for h in gens:
            x = compose(h, g)
            if x not in group:
                group.add(x)
                todo.append(x)
    return frozenset(group)


def sets_of_permutations(name, n):
    """The sets of permutations of a shuffle class, or None for arbitrary sets of permutations.

    transposition  {id, tau} for a transposition tau
    rbc            {id, tau_1 ... tau_{n/2}} for pairwise disjoint transpositions; since every
                   shuffle is preceded by an arbitrary rearrangement, these give random
                   bisection cuts
    closed         all subgroups of S_n (every subgroup of S_3 and S_4 has two generators)
    rc             the cyclic groups generated by an n-cycle; these give random cuts
    arbitrary      any nonempty subset of S_n
    """
    perms = all_perms(n)
    identity = tuple(range(n))

    def is_involution(p):
        return p != identity and all(p[p[j]] == j for j in range(n))

    def moved(p):
        return sum(p[j] != j for j in range(n))

    if name == 'arbitrary':
        return None
    if name == 'transposition':
        return [frozenset({identity, p}) for p in perms if is_involution(p) and moved(p) == 2]
    if name == 'rbc':
        return [frozenset({identity, p}) for p in perms if is_involution(p) and moved(p) == n]
    if name == 'closed':
        return sorted({generated_group(gens, n) for size in (1, 2)
                       for gens in itertools.combinations(perms, size)}, key=len)
    if name == 'rc':
        cycles = [p for p in perms if moved(p) == n and len(generated_group([p], n)) == n]
        return sorted({generated_group([p], n) for p in cycles}, key=sorted)
    raise ValueError(f'unknown shuffle class: {name}')


class QBF:
    """A prenex QBF in conjunctive normal form, written in QDIMACS."""

    def __init__(self, quantifiers):
        self.num_vars = 0
        self.blocks = [(q, []) for q in quantifiers]
        self.clauses = []

    def var(self, block):
        self.num_vars += 1
        self.blocks[block][1].append(self.num_vars)
        return self.num_vars

    def add(self, *lits):
        self.clauses.append(lits)

    def exactly_one(self, vs, guard=()):
        """At-least-one clause and pairwise at-most-one clauses, each extended by the guard."""
        self.add(*guard, *vs)
        for v1, v2 in itertools.combinations(vs, 2):
            self.add(*guard, -v1, -v2)

    def iff(self, v1, v2, guard=()):
        self.add(*guard, -v1, v2)
        self.add(*guard, v1, -v2)

    def write(self, path, comments=()):
        with open(path, 'w') as fh:
            for c in comments:
                fh.write(f'c {c}\n')
            fh.write(f'p cnf {self.num_vars} {len(self.clauses)}\n')
            for q, vs in self.blocks:
                if vs:
                    fh.write(q + ' ' + ' '.join(map(str, vs)) + ' 0\n')
            for clause in self.clauses:
                fh.write(' '.join(map(str, clause)) + ' 0\n')


def build(cards, k, shuffle_class, security=True):
    """Build formula (1) (security=True) or formula (2) (security=False) for AND."""
    n, layout = LAYOUTS[cards]
    P = all_perms(n)
    classes = sets_of_permutations(shuffle_class, n)
    num_bits = max(1, math.ceil(math.log2(len(P))))
    q = QBF(['e', 'a', 'e', 'a', 'e'] if security else ['e', 'a', 'e'])

    # ---- Quantifier block 1 (exists): the protocol variables P ----
    s = [[q.var(0) for _ in P] for _ in range(k)]      # s[l][i]: the l-th rearrangement is P[i]
    m = [[q.var(0) for _ in P] for _ in range(k)]      # m[l][i]: P[i] is in the set of permutations
    for l in range(k):
        q.exactly_one(s[l])
        if classes is None:
            q.add(*m[l])                               # a nonempty set of permutations
        else:
            c = [q.var(0) for _ in classes]            # c[l][S]: the set of permutations is S
            q.exactly_one(c)
            for c_S, S in zip(c, classes):
                for pi, m_pi in zip(P, m[l]):
                    q.add(-c_S, m_pi if pi in S else -m_pi)
    subsets = [T for size in range(n) for T in itertools.combinations(range(n), size)]
    u = {T: q.var(0) for T in subsets}                 # u[T]: the turned set is T
    q.exactly_one(list(u.values()))
    r = {}                                             # r[T, v][p]: R(T, v) = p
    for T in subsets:
        rest = [p for p in range(n) if p not in T]
        for v in itertools.product((0, 1), repeat=len(T)):
            r[T, v] = {p: q.var(0) for p in rest}
            q.exactly_one(list(r[T, v].values()))

    # ---- Quantifier block 2 (forall): the input and the outcomes O (bits F) ----
    a, b = q.var(1), q.var(1)
    F = [[q.var(1) for _ in range(num_bits)] for _ in range(k)]

    # ---- Quantifier block 3 (exists): auxiliary variables and the execution X ----
    g = q.var(2)                                       # g: all outcomes lie in their sets
    guard = (-g,)                                      # adding -g expresses "Valid(O) -> ..."
    z = q.var(2)                                       # z <-> f(a, b) = a AND b, part of Correct
    q.add(*guard, -z, a)
    q.add(*guard, -z, b)
    q.add(*guard, z, -a, -b)
    e, w = [], []
    for l in range(k):
        e_l = [q.var(2) for _ in P]                    # e[l][i] <-> (F_l = i)
        for i, e_li in enumerate(e_l):
            bits = [F[l][t] if (i >> t) & 1 else -F[l][t] for t in range(num_bits)]
            for lit in bits:
                q.add(-e_li, lit)
            q.add(e_li, *[-lit for lit in bits])
        w_l = q.var(2)                                 # w[l]: the l-th outcome lies in its set
        for e_li, m_li in zip(e_l, m[l]):
            q.add(-e_li, -m_li, w_l)
        e.append(e_l)
        w.append(w_l)
    q.add(*[-w_l for w_l in w], g)

    def trace(block, in_a, in_b, outcome):
        """Card variables of one execution; returns the values after the last shuffle."""
        x = [q.var(block) for _ in range(n)]          # x0[j]: the value at position j at the start
        for j, (kind, arg) in enumerate(layout):
            if kind == 'c':
                q.add(*guard, x[j] if arg else -x[j])
            else:
                value = in_a if kind == 'a' else in_b
                q.iff(x[j], value if arg == 0 else -value, guard)
        for l in range(k):
            y = [q.var(block) for _ in range(n)]      # after the l-th rearrangement
            for s_li, pi in zip(s[l], P):
                for j in range(n):
                    q.iff(y[pi[j]], x[j], guard + (-s_li,))
            x_next = [q.var(block) for _ in range(n)]  # after the l-th shuffle
            for e_li, pi in zip(outcome[l], P):
                for j in range(n):
                    q.iff(x_next[pi[j]], y[j], guard + (-e_li,))
            x = x_next
        return x

    x = trace(2, a, b, e)

    # Correct(x): u_T & r_{T,v,p} & (x|T = v) -> (x_p <-> z)
    for T in subsets:
        for v in itertools.product((0, 1), repeat=len(T)):
            differs = [x[j] if v_j == 0 else -x[j] for j, v_j in zip(T, v)]
            for p, r_p in r[T, v].items():
                premise = guard + (-u[T], -r_p, *differs)
                q.add(*premise, -x[p], z)
                q.add(*premise, x[p], -z)

    # ---- Quantifier blocks 4 (forall) and 5 (exists): possibilistic security ----
    if security:
        a2, b2 = q.var(3), q.var(3)
        e2 = []
        for l in range(k):
            e2_l = [q.var(4) for _ in P]               # the l-th outcome of the second execution
            q.exactly_one(e2_l, guard)
            for e2_li, m_li in zip(e2_l, m[l]):
                q.add(*guard, -e2_li, m_li)            # Valid(O')
            e2.append(e2_l)
        x2 = trace(4, a2, b2, e2)
        for T in subsets:                              # Same(X, X')
            for j in T:
                q.iff(x2[j], x[j], guard + (-u[T],))

    info = {'n': n, 'P': P, 'k': k, 's': s, 'm': m, 'u': u, 'r': r}
    return q, info


def cycle_notation(p):
    """Cycle notation of p with 1-based positions, e.g. '(1 2)(3 4)'; 'id' for the identity."""
    seen, out = set(), []
    for start in range(len(p)):
        if start in seen or p[start] == start:
            continue
        cycle, j = [], start
        while j not in seen:
            seen.add(j)
            cycle.append(str(j + 1))
            j = p[j]
        out.append('(' + ' '.join(cycle) + ')')
    return ''.join(out) or 'id'


def decode(info, true_vars):
    """The protocol given by the values of the block-1 variables of a true formula."""
    P, k = info['P'], info['k']
    lines = []
    for l in range(k):
        rearr = [pi for pi, v in zip(P, info['s'][l]) if v in true_vars]
        perm_set = [pi for pi, v in zip(P, info['m'][l]) if v in true_vars]
        lines.append(f'(perm, {cycle_notation(rearr[0])})')
        lines.append('(shuffle, {' + ', '.join(cycle_notation(pi) for pi in perm_set) + '})')
    T = next(T for T, v in info['u'].items() if v in true_vars)
    lines.append('(turn, {' + ', '.join(str(j + 1) for j in T) + '})')
    for (T2, vis), r_T in info['r'].items():
        if T2 != T:
            continue
        p = next(p for p, v in r_T.items() if v in true_vars)
        shown = ''.join('♣♡'[x] for x in vis) or 'nothing'
        lines.append(f'  if the turned cards show {shown}: (result, {p + 1})')
    return lines


def instance_name(cards, k, shuffle_class, security):
    return f'n{cards}_k{k}_{shuffle_class}_{"sec" if security else "nosec"}'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--cards', type=int, choices=sorted(LAYOUTS), default=3,
                    help='3: (a, b, not b); 4: (club, a, b, not b)')
    ap.add_argument('--blocks', type=int, default=1, help='number k of shuffles, each preceded by a rearrangement')
    ap.add_argument('--shuffles', choices=SHUFFLE_CLASSES, default='arbitrary', help='class of shuffles')
    ap.add_argument('--no-security', action='store_true', help='formula (2): correctness only')
    ap.add_argument('-o', '--out', help='output file (default: <instance name>.qdimacs)')
    args = ap.parse_args()
    security = not args.no_security
    name = instance_name(args.cards, args.blocks, args.shuffles, security)
    path = args.out or name + '.qdimacs'
    q, _ = build(args.cards, args.blocks, args.shuffles, security)
    q.write(path, [f'{name}: cards={args.cards} blocks={args.blocks} shuffles={args.shuffles} '
                   f'security={"yes" if security else "no"}'])
    print(f'{path}: {q.num_vars} variables, {len(q.clauses)} clauses')


if __name__ == '__main__':
    main()
